$("#saveSecretBtn").onclick=()=>{
  const raw=$("#secretInput").value.trim();
  if(!raw){alert("Enter a key/token for this prototype connection test.");return}
  const last4=raw.slice(-4);
  const id=pendingProvider.toLowerCase().replace(/\s+/g,"");
  const status=document.getElementById(id+"Status");
  if(status){status.textContent="Connected ••••"+last4;status.classList.add("good")}
  // Deliberately DO NOT persist raw secret in this prototype.
  $("#secretInput").value="";
  $("#secretEntry").hidden=true;
  alert("Prototype connection sealed. Raw secret was not persisted. Production ForgeBoss must use OS-protected secret storage or OAuth.");
};

