function detectProvider(url){
  if(/github\.com/i.test(url)) return "GitHub";
  if(/gitlab/i.test(url)) return "GitLab";
  if(/bitbucket/i.test(url)) return "Bitbucket";
  if(/dev\.azure\.com|visualstudio\.com/i.test(url)) return "Azure DevOps";
  return url ? "Generic Git" : "not detected";
}
$("#detectRepoBtn").onclick=()=>{
  $("#providerStatus").textContent="Provider: "+detectProvider($("#repoInput").value.trim());
};
$("#loadRepoBtn").onclick=()=>{
  const u=$("#repoInput").value.trim(); if(!u){alert("Paste a repository link first.");return}
  const parts=u.replace(/\.git$/,"").replace(/\/$/,"").split("/");
  setProject(parts[parts.length-1]||"Remote project");
  showPage("vault");
};

function saveChats(){localStorage.setItem("fb_chats",JSON.stringify(chats));renderChats()}
function renderChats(){
  const host=$("#chatStream");
  if(!chats.length){
    chats=[{role:"bot",text:"Forge Chat is project-aware. Tell me ideas, decisions, changes or questions. Important decisions can be promoted into the Bible; casual discussion stays in memory.",time:""}];
  }
  host.innerHTML=chats.map(c=>`<div class="bubble ${c.role}">${escapeHtml(c.text)}<small>${c.time||""}</small></div>`).join("");
  host.scrollTop=host.scrollHeight;
}
function escapeHtml(s){return s.replace(/[&<>"']/g,m=>({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"}[m]))}
renderChats();
$("#sendChatBtn").onclick=()=>{
  const t=$("#chatInput").value.trim(); if(!t)return;
  const time=new Date().toLocaleTimeString([], {hour:"2-digit",minute:"2-digit"});
  chats.push({role:"user",text:t,time});
  chats.push({role:"bot",text:"Saved to this project's conversation memory. If that changes an authoritative requirement, ForgeBoss would flag it for Bible promotion rather than silently rewriting the project.",time});
  $("#chatInput").value=""; saveChats();
};

